import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const rootPath = fileURLToPath(new URL("..", import.meta.url));
const outputPath = join(rootPath, "dist", "offline-assets.json");
const packageJson = JSON.parse(readFileSync(join(rootPath, "package.json"), "utf8"));

function readSoundEvents() {
  const soundMapSource = readFileSync(join(rootPath, "src", "audio", "soundMap.ts"), "utf8");
  const objectBody = soundMapSource.match(/SOUND_EVENT_MAP\s*=\s*\{([\s\S]*?)\}\s*as const/)?.[1] ?? "";

  return [...objectBody.matchAll(/^\s*([A-Za-z][A-Za-z0-9_]*)\s*:/gm)].map((match) => match[1]);
}

const dataFiles = readdirSync(join(rootPath, "data"))
  .filter((name) => name.endsWith(".json"))
  .sort()
  .map((name) => `data/${name}`);

const manifest = {
  name: "program-c-offline-assets",
  version: packageJson.version,
  offlineReady: true,
  externalNetworkRequired: false,
  runtimeEntrypoints: [
    "src/content/index.ts",
    "src/audio/index.ts",
  ],
  requiredFiles: [
    ...dataFiles,
    "dist/content-manifest.json",
  ],
  audio: {
    mode: "web-audio-procedural",
    externalFiles: [],
    events: readSoundEvents(),
  },
  notes: [
    "Program C does not require remote API calls for core gameplay decisions.",
    "Audio is generated by Web Audio API, so no audio asset download is required.",
  ],
};

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
console.log(`Wrote ${outputPath}`);
